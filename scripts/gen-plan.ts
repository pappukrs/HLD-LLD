// Generates plan/weeks/*.md, shared/plan-data.js (for the hub) and CATALOG.md
// from plan/curriculum.ts and plan/concepts.ts.
// Run: npm run plan
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CONCEPTS, MODULES, conceptDir } from '../plan/concepts';
import { END, PHASES, START, WEEKS, type Task } from '../plan/curriculum';
import { dateOf, DAY_NAMES, minutes, pad2, phaseLabel, prettyDate, TOTAL_DAYS } from '../plan/lib';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const WEEKS_DIR = join(ROOT, 'plan', 'weeks');
mkdirSync(WEEKS_DIR, { recursive: true });

const missing = new Set<string>();

function link(path: string, fromDir: string): string {
  const clean = path.replace(/\/$/, '');
  if (!existsSync(join(ROOT, clean))) missing.add(path);
  const rel = relative(fromDir, join(ROOT, clean)) + (path.endsWith('/') ? '/' : '');
  const file = clean.split('/').pop()!;
  const label = file === 'README.md' || file === 'my-design.md' ? clean.split('/').slice(-2).join('/') : file === 'visual.html' ? 'visual' : file === 'demo.ts' ? 'demo.ts' : file;
  return `[${label}](${rel})`;
}

function taskLine(task: Task, fromDir: string, stretch = false): string {
  const links = task.links.map((l) => link(l, fromDir)).join(' · ');
  const tag = stretch ? 'Stretch' : task.track;
  return `- [ ] **${tag} · ${task.minutes} min**: ${task.title}${links ? `  \n  ${links}` : ''}  \n  _${task.todo}_`;
}

// ---- weekly markdown ----
let dayNumber = 0;
WEEKS.forEach((week, wi) => {
  const n = wi + 1;
  const total = week.days.reduce((s, d) => s + minutes(d), 0);
  const lines: string[] = [
    `# Week ${n} · ${week.theme}`,
    '',
    `> ${prettyDate(dateOf(wi * 7 + 1))} – ${prettyDate(dateOf(wi * 7 + 7))} · ${phaseLabel(week)} · ~${Math.round(total / 60)} h this week`,
    `> **Goal:** ${week.goal}`,
    '',
    [n > 1 ? `[← Week ${n - 1}](week-${pad2(n - 1)}.md)` : '', '[All weeks](README.md)', n < WEEKS.length ? `[Week ${n + 1} →](week-${pad2(n + 1)}.md)` : ''].filter(Boolean).join(' · '),
    '',
  ];
  week.days.forEach((day, di) => {
    dayNumber++;
    lines.push(`## ${DAY_NAMES[di]} ${prettyDate(dateOf(dayNumber)).replace(/^\w+ /, '')} · Day ${dayNumber} · ${minutes(day)} min`, '');
    day.tasks.forEach((t) => lines.push(taskLine(t, WEEKS_DIR)));
    if (day.stretch) lines.push(taskLine(day.stretch, WEEKS_DIR, true));
    lines.push('');
  });
  if (week.gate) {
    lines.push('## Gate: pass this before moving on', '');
    week.gate.forEach((g) => lines.push(`- [ ] ${g}`));
    lines.push('', "Not passing? Repeat the weakest week's Saturday and Sunday before starting the next phase. Moving on with gaps costs more later.", '');
  }
  lines.push('## Notes', '', '_Write what was hard this week, what to repeat, and anything from interviews._', '');
  writeFileSync(join(WEEKS_DIR, `week-${pad2(n)}.md`), lines.join('\n'));
});

const index: string[] = [
  '# All weeks',
  '',
  `${START} → ${END} · ${TOTAL_DAYS} days. Generated from [curriculum.ts](../curriculum.ts) by \`npm run plan\`. Don't edit these files by hand except to tick boxes and write notes.`,
  '',
  '| Week | Dates | Phase | Theme |',
  '|---|---|---|---|',
];
WEEKS.forEach((w, i) => {
  index.push(`| [${i + 1}](week-${pad2(i + 1)}.md) | ${prettyDate(dateOf(i * 7 + 1))} – ${prettyDate(dateOf(i * 7 + 7))} | ${w.phase} · ${PHASES[w.phase].name} | ${w.theme}${w.gate ? ' · **gate**' : ''} |`);
});
writeFileSync(join(WEEKS_DIR, 'README.md'), index.join('\n') + '\n');

// ---- data for the hub (classic script so it works from file://) ----
const scheduled = new Map<string, number>(); // concept id -> day number
WEEKS.forEach((w, wi) => w.days.forEach((d, di) => d.tasks.forEach((t) => t.concept && !scheduled.has(t.concept) && scheduled.set(t.concept, wi * 7 + di + 1))));
const data = {
  start: START,
  end: END,
  phases: PHASES,
  modules: MODULES,
  concepts: CONCEPTS.map((x) => ({ ...x, dir: conceptDir(x), day: scheduled.get(x.id) ?? null })),
  weeks: WEEKS.map((w) => ({ phase: w.phase, theme: w.theme, goal: w.goal, gate: w.gate ?? null, days: w.days.map((d) => ({ tasks: d.tasks, stretch: d.stretch ?? null })) })),
};
writeFileSync(join(ROOT, 'shared', 'plan-data.js'), `// Generated by \`npm run plan\` from plan/. Do not edit.\nwindow.PLAN = ${JSON.stringify(data)};\n`);

// ---- CATALOG.md ----
const titleOf = (readme: string) => {
  const p = join(ROOT, readme);
  if (!existsSync(p)) return null;
  const h = readFileSync(p, 'utf8').split('\n').find((l) => l.startsWith('# '));
  return h ? h.replace(/^#\s+(\d+\s*·\s*)?/, '') : null;
};
const listDirs = (d: string) => readdirSync(join(ROOT, d), { withFileTypes: true }).filter((e) => e.isDirectory() && !e.name.startsWith('_')).map((e) => e.name).sort();
const cat: string[] = ['# Catalog', '', 'Every concept, problem and lab, with its path. Generated by `npm run plan` from [plan/concepts.ts](plan/concepts.ts).', ''];
for (const track of ['LLD', 'HLD'] as const) {
  cat.push(`## ${track} concepts`, '');
  for (const m of MODULES.filter((m) => m.track === track)) {
    cat.push(`### ${m.title} · \`${m.dir}/\``, '', `_${m.why}_`, '', '| ID | Concept | Notes | Visual | Code | Extra | Day |', '|---|---|---|---|---|---|---|');
    for (const x of CONCEPTS.filter((x) => x.module === m.dir)) {
      const d = conceptDir(x);
      const extra = [...(x.labs ?? []).map((l) => `[${l}](${d}/${l}/README.md)`), ...(x.handsOn ? [`[hands-on](${d}/hands-on/)`] : [])].join(' · ');
      cat.push(`| ${x.id} | ${x.title} | [README](${d}/README.md) | [visual](${d}/visual.html) | [demo.ts](${d}/demo.ts) | ${extra} | ${scheduled.get(x.id) ?? ''} |`);
    }
    cat.push('');
  }
}
cat.push('## LLD problems · `lld/problems/` (README, starter.ts, reference.ts, tests)', '', '| Problem | Title |', '|---|---|');
listDirs('lld/problems').forEach((p) => cat.push(`| [${p}](lld/problems/${p}/README.md) | ${titleOf(`lld/problems/${p}/README.md`) ?? ''} |`));
cat.push('', '## HLD case studies · `hld/case-studies/` (README with hidden hints + my-design.md)', '', '| Case study | Title |', '|---|---|');
listDirs('hld/case-studies').forEach((p) => cat.push(`| [${p}](hld/case-studies/${p}/README.md) | ${titleOf(`hld/case-studies/${p}/README.md`) ?? ''} |`));
cat.push('', 'Advanced list for the interview-loop phase: [hld/case-studies/advanced-37.md](hld/case-studies/advanced-37.md)', '');
writeFileSync(join(ROOT, 'CATALOG.md'), cat.join('\n'));

console.log(`Wrote ${WEEKS.length} weeks (${TOTAL_DAYS} days) to plan/weeks/, shared/plan-data.js and CATALOG.md`);
if (missing.size) {
  console.log(`\n${missing.size} linked paths don't exist yet:`);
  [...missing].sort().forEach((m) => console.log('  - ' + m));
  process.exitCode = 1;
}
