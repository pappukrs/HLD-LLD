// Generates plan/weeks/*.md and visuals/plan-data.js from plan/curriculum.ts.
// Run: npm run plan
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { END, PHASES, START, WEEKS, type Task } from '../plan/curriculum';
import { dateOf, DAY_NAMES, minutes, pad2, phaseLabel, prettyDate, TOTAL_DAYS } from '../plan/lib';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const WEEKS_DIR = join(ROOT, 'plan', 'weeks');
mkdirSync(WEEKS_DIR, { recursive: true });

const missing = new Set<string>();

function link(path: string, fromDir: string): string {
  const clean = path.replace(/\/$/, '');
  if (!existsSync(join(ROOT, clean))) missing.add(path);
  const rel = relative(fromDir, join(ROOT, clean)) + (path.endsWith('/') ? '/' : '');
  const label = clean.split('/').slice(-2).join('/').replace(/\/README\.md$/, '').replace(/\.md$/, '');
  return `[${label}](${rel})`;
}

function taskLine(task: Task, fromDir: string, stretch = false): string {
  const links = task.links.map((l) => link(l, fromDir)).join(' · ');
  const tag = stretch ? 'Stretch' : task.track;
  return `- [ ] **${tag} · ${task.minutes} min**: ${task.title}${links ? `  \n  ${links}` : ''}  \n  _${task.todo}_`;
}

// ---- weekly markdown ----
let dayNumber = 0;
WEEKS.forEach((week, wi) => {
  const n = wi + 1;
  const first = dateOf(wi * 7 + 1);
  const last = dateOf(wi * 7 + 7);
  const total = week.days.reduce((s, d) => s + minutes(d), 0);
  const lines: string[] = [
    `# Week ${n} · ${week.theme}`,
    '',
    `> ${prettyDate(first)} – ${prettyDate(last)} · ${phaseLabel(week)} · ~${Math.round(total / 60)} h this week`,
    `> **Goal:** ${week.goal}`,
    '',
    n > 1 ? `[← Week ${n - 1}](week-${pad2(n - 1)}.md) · [All weeks](README.md)${n < WEEKS.length ? ` · [Week ${n + 1} →](week-${pad2(n + 1)}.md)` : ''}` : `[All weeks](README.md) · [Week 2 →](week-02.md)`,
    '',
  ];
  week.days.forEach((day, di) => {
    dayNumber++;
    lines.push(`## ${DAY_NAMES[di]} ${prettyDate(dateOf(dayNumber)).replace(/^\w+ /, '')} · Day ${dayNumber} · ${minutes(day)} min`, '');
    day.tasks.forEach((t) => lines.push(taskLine(t, WEEKS_DIR)));
    if (day.stretch) lines.push(taskLine(day.stretch, WEEKS_DIR, true));
    lines.push('');
  });
  if (week.gate) {
    lines.push(`## Gate: pass this before moving on`, '');
    week.gate.forEach((g) => lines.push(`- [ ] ${g}`));
    lines.push('', 'Not passing? Repeat the weakest week\'s Saturday and Sunday before starting the next phase. Moving on with gaps costs more later.', '');
  }
  lines.push('## Notes', '', '_Write what was hard this week, what to repeat, and anything from interviews._', '');
  writeFileSync(join(WEEKS_DIR, `week-${pad2(n)}.md`), lines.join('\n'));
});

// ---- index ----
const index: string[] = [
  '# All weeks',
  '',
  `${START} → ${END} · ${TOTAL_DAYS} days. Generated from [curriculum.ts](../curriculum.ts) by \`npm run plan\`. Don't edit these files by hand except to tick boxes and write notes.`,
  '',
  '| Week | Dates | Phase | Theme |',
  '|---|---|---|---|',
];
WEEKS.forEach((w, i) => {
  index.push(`| [${i + 1}](week-${pad2(i + 1)}.md) | ${prettyDate(dateOf(i * 7 + 1))} – ${prettyDate(dateOf(i * 7 + 7))} | ${w.phase} · ${PHASES[w.phase].name} | ${w.theme}${w.gate ? ' · **gate**' : ''} |`);
});
writeFileSync(join(WEEKS_DIR, 'README.md'), index.join('\n') + '\n');

// ---- data for the visuals hub (classic script so it works from file://) ----
const data = {
  start: START,
  end: END,
  phases: PHASES,
  weeks: WEEKS.map((w) => ({
    phase: w.phase,
    theme: w.theme,
    goal: w.goal,
    gate: w.gate ?? null,
    days: w.days.map((d) => ({ tasks: d.tasks, stretch: d.stretch ?? null })),
  })),
};
writeFileSync(
  join(ROOT, 'visuals', 'plan-data.js'),
  `// Generated by \`npm run plan\` from plan/curriculum.ts. Do not edit.\nwindow.PLAN = ${JSON.stringify(data)};\n`,
);

console.log(`Wrote ${WEEKS.length} weeks (${TOTAL_DAYS} days) to plan/weeks/ and visuals/plan-data.js`);
if (missing.size) {
  console.log(`\n${missing.size} linked paths don't exist yet:`);
  [...missing].sort().forEach((m) => console.log('  - ' + m));
  process.exitCode = 1;
}
